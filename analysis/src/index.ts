// Summarizes raw benchmark results into tables, threshold crossings, and figures.
// Usage: node analysis/src/index.ts --runs <raw folder> --out <output folder>
//        [--compare <raw folder> --compare-label "Visible window"]
// The output folder receives runs.csv, scenarios.csv, report.md, and figures/*.svg.
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { parseArgs } from 'node:util';
import { plotMetric, type PlotOptions } from './plot.ts';
import { comparisonTable, crossingsTable, metricTable, qualityReport, runsCsv, scenariosCsv } from './report.ts';
import { readRawSet, summarizeRun } from './runs.ts';
import { summarizeScenarios } from './scenarios.ts';
import { findCrossings } from './thresholds.ts';

const { values: args } = parseArgs({
  options: {
    runs: { type: 'string' },
    out: { type: 'string' },
    compare: { type: 'string' },
    'base-label': { type: 'string', default: 'Headless' },
    'compare-label': { type: 'string', default: 'Visible window' },
  },
});
if (!args.runs || !args.out) throw new Error('--runs and --out are required');

const FIGURES: (PlotOptions & { file: string })[] = [
  { file: 'frame-time-p95.svg', metric: 'frameP95', title: 'Frame time, 95th percentile', yLabel: 'Frame time p95 (ms, log scale)', scale: 'log', threshold: { value: 25, label: 'Frame budget (25 ms)' } },
  { file: 'late-frames.svg', metric: 'lateFrameShare', title: 'Share of late frames', yLabel: 'Frames over 25 ms (share)', scale: 'linear' },
  { file: 'send-to-paint-median.svg', metric: 'sendToPaintMedian', title: 'Send-to-paint latency, median', yLabel: 'Latency median (ms, log scale)', scale: 'log' },
  { file: 'send-to-paint-p95.svg', metric: 'sendToPaintP95', title: 'Send-to-paint latency, 95th percentile', yLabel: 'Latency p95 (ms, log scale)', scale: 'log', threshold: { value: 1000, label: '1 s' } },
  { file: 'interaction-p95.svg', metric: 'interactionP95', title: 'Interaction responsiveness, 95th percentile', yLabel: 'Input to next frame p95 (ms, log scale)', scale: 'log', threshold: { value: 100, label: '0.1 s' } },
  { file: 'memory-median.svg', metric: 'memoryMedianMiB', title: 'Browser process memory, median', yLabel: 'Process memory (MiB)', scale: 'linear' },
];

const base = await readRawSet(args.runs);
const runs = base.runs.map(summarizeRun);
const scenarios = summarizeScenarios(runs);
const crossings = findCrossings(scenarios);

await mkdir(path.join(args.out, 'figures'), { recursive: true });
await writeFile(path.join(args.out, 'runs.csv'), runsCsv(runs));
await writeFile(path.join(args.out, 'scenarios.csv'), scenariosCsv(scenarios));
for (const figure of FIGURES) {
  await writeFile(path.join(args.out, 'figures', figure.file), plotMetric(scenarios, figure));
}

const report: string[] = [
  `# Analysis of ${path.basename(path.resolve(args.runs))}`,
  '',
  `Source: \`${args.runs}\`, ${base.manifest.headless ? 'headless' : 'visible window'}, commit ${base.manifest.environment.gitCommit.slice(0, 7)}${base.manifest.environment.gitDirty ? ' (uncommitted changes)' : ''}.`,
  'Generated by `analysis/src/index.ts`. Do not edit by hand; rerun the script instead.',
  '',
  '## Data quality',
  '',
  qualityReport(runs),
  '',
  '## Threshold crossings',
  '',
  crossingsTable(crossings),
  '',
  '## Tables',
  '',
  metricTable(scenarios, 'frameP95', 'Frame time, 95th percentile (ms).'),
  '',
  metricTable(scenarios, 'lateFrameShare', 'Late frames (% of frames over 25 ms).', 1, 100),
  '',
  metricTable(scenarios, 'sendToPaintMedian', 'Send-to-paint latency, median (ms).', 0),
  '',
  metricTable(scenarios, 'sendToPaintP95', 'Send-to-paint latency, 95th percentile (ms).', 0),
  '',
  metricTable(scenarios, 'interactionP95', 'Interaction responsiveness, 95th percentile (ms).', 0),
  '',
  metricTable(scenarios, 'memoryMedianMiB', 'Browser process memory, median (MiB).', 0),
  '',
  metricTable(scenarios, 'heapMedianMiB', 'Main-thread heap, median (MiB).', 1),
];

if (args.compare) {
  const other = await readRawSet(args.compare);
  const otherRuns = other.runs.map(summarizeRun);
  const otherScenarios = summarizeScenarios(otherRuns);
  await writeFile(path.join(args.out, 'compare-runs.csv'), runsCsv(otherRuns));
  report.push(
    '',
    `## ${args['base-label']} compared with ${args['compare-label']}`,
    '',
    `Comparison set: \`${args.compare}\`, commit ${other.manifest.environment.gitCommit.slice(0, 7)}.`,
    '',
    qualityReport(otherRuns),
    '',
    comparisonTable(scenarios, otherScenarios, [args['base-label']!, args['compare-label']!]),
  );
}

await writeFile(path.join(args.out, 'report.md'), `${report.join('\n')}\n`);
console.log(`Wrote ${runs.length} runs, ${scenarios.length} scenarios to ${args.out}`);
